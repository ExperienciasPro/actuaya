export type TransactionType = 'ingreso' | 'egreso';

export type TransactionCategory =
  | 'ventas'
  | 'servicios'
  | 'cobros'
  | 'inversiones'
  | 'arriendos_recibidos'
  | 'salario'
  | 'pension'
  | 'otros_ingresos'
  | 'nomina'
  | 'arriendos'
  | 'servicios_publicos'
  | 'proveedores'
  | 'impuestos'
  | 'marketing'
  | 'transporte'
  | 'salud'
  | 'telefonia'
  | 'internet'
  | 'alimentacion'
  | 'creditos'
  | 'educacion'
  | 'seguros'
  | 'otros_egresos';

export interface Transaction {
  id: string;
  type: TransactionType;
  category: TransactionCategory;
  description: string;
  amount: number;              // always positive
  currency?: string;           // 'COP' | 'USD' — defaults to 'COP'
  date: string;                // ISO date YYYY-MM-DD
  createdAt: string;           // ISO datetime
  updatedAt?: string;
  isDeleted?: boolean;
  notes?: string;
  linkedProductId?: string;    // ID del producto en inventario
  linkedQuantity?: number;     // Cantidad de unidades
  autoGenerated?: boolean;     // Generado de forma automática por el sistema
  sourceQuoteId?: string;      // ID de la cotización de origen
  recurringExpenseId?: string; // ID del egreso básico mensual que lo originó
}

export interface CashflowSummary {
  totalIngresos: number;
  totalEgresos: number;
  balance: number;
  transactionCount: number;
}

